import { supabase } from '../config/supabase.js';

export async function fetchActiveGoldSignals(req, res) {
  try {
    // The client EA sends its unique user API token in the Authorization or x-api-token header
    const apiToken = req.headers['x-api-token'] || req.headers['authorization']?.replace('Bearer ', '');

    if (!apiToken) {
      return res.status(401).json({ success: false, error: 'Missing API Token' });
    }

    // 1. Verify user exists and retrieve their ID using client_id / api token
    const { data: user, error: userError } = await supabase
      .from('users')
      .select('id, client_id')
      .eq('client_id', apiToken)
      .single();

    if (userError || !user) {
      return res.status(403).json({ success: false, error: 'Invalid API Token' });
    }

    // 2. Check if the user has an active EA subscription (plan_type containing 'ea' or 'bundle')
    const { data: sub, error: subError } = await supabase
      .from('subscriptions')
      .select('status, plan_type, current_period_end')
      .eq('user_id', user.id)
      .single();

    if (subError || !sub || sub.status !== 'active') {
      return res.status(403).json({ success: false, error: 'Active EA Auto-Execution subscription required.' });
    }

    // Ensure their specific plan covers EA execution
    const isEaPlan = sub.plan_type.includes('ea') || sub.plan_type.includes('bundle');
    if (!isEaPlan) {
      return res.status(403).json({ success: false, error: 'Current subscription plan does not include EA Auto-Execution.' });
    }

    // 3. Fetch latest active PENDING Gold (XAUUSD) signals generated by your xauEngine
    const { data: signals, error: signalError } = await supabase
      .from('signals')
      .select('*')
      .eq('pair', 'XAUUSD')
      .eq('status', 'PENDING')
      .order('created_at', { ascending: false })
      .limit(1);

    if (signalError) throw signalError;

    return res.status(200).json({
      success: true,
      server_time: new Date().toISOString(),
      signals: signals || []
    });

  } catch (err) {
    console.error('[EA_EXECUTION_FETCH_ERROR]:', err.message);
    return res.status(500).json({ success: false, error: 'Internal server error' });
  }
}